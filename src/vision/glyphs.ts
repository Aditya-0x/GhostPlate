/**
 * Sample the 7x11 bitmap pattern with smooth bilinear anti-aliasing so scaled
 * glyphs look like real embossed plate characters rather than blocky pixels.
 */
export function sampleGlyphAlpha(char: string, u: number, v: number): number {
  const pattern = GLYPH_PATTERNS[char.toUpperCase()];
  if (!pattern) return 0;
  const rows = pattern.length; // 11
  const cols = pattern[0].length; // 7

  const fx = u * cols - 0.5;
  const fy = v * rows - 0.5;
  const x0 = Math.floor(fx);
  const y0 = Math.floor(fy);
  const dx = fx - x0;
  const dy = fy - y0;

  const val = (x: number, y: number): number => {
    if (x < 0 || x >= cols || y < 0 || y >= rows) return 0;
    return pattern[y][x] === '#' ? 1 : 0;
  };

  const v00 = val(x0, y0);
  const v10 = val(x0 + 1, y0);
  const v01 = val(x0, y0 + 1);
  const v11 = val(x0 + 1, y0 + 1);

  const interp =
    v00 * (1 - dx) * (1 - dy) +
    v10 * dx * (1 - dy) +
    v01 * (1 - dx) * dy +
    v11 * dx * dy;

  // Smooth step sharpening for crisp anti-aliased plate strokes
  if (interp <= 0.28) return 0;
  if (interp >= 0.62) return 1;
  const t = (interp - 0.28) / (0.62 - 0.28);
  return t * t * (3 - 2 * t);
}

/**
 * Render a canonical 32x32 centered character prototype (white on black)
 * matching the exact normalization geometry used by src/vision/segment.ts.
 */
export function renderCanonicalGlyph32(char: string): GrayBuffer {
  const size = 32;
  const data = new Uint8Array(size * size);
  const targetH = 26;
  const targetW = Math.round(targetH * (7 / 11)); // ~17px
  const offX = Math.floor((size - targetW) / 2);
  const offY = Math.floor((size - targetH) / 2);

  for (let y = 0; y < targetH; y++) {
    const v = (y + 0.5) / targetH;
    for (let x = 0; x < targetW; x++) {
      const u = (x + 0.5) / targetW;
      const alpha = sampleGlyphAlpha(char, u, v);
      data[(offY + y) * size + (offX + x)] = Math.round(alpha * 255);
    }
  }
  return { width: size, height: size, data };
}

/**
 * Draw a crisp anti-aliased glyph directly onto an RGBA buffer.
 */
export function drawGlyphOnRgba(
  data: Uint8ClampedArray,
  bufW: number,
  bufH: number,
  char: string,
  x0: number,
  y0: number,
  glyphW: number,
  glyphH: number,
  color: [number, number, number]
): void {
  const startX = Math.max(0, Math.floor(x0));
  const endX = Math.min(bufW, Math.ceil(x0 + glyphW));
  const startY = Math.max(0, Math.floor(y0));
  const endY = Math.min(bufH, Math.ceil(y0 + glyphH));

  for (let y = startY; y < endY; y++) {
    const v = (y - y0 + 0.5) / glyphH;
    for (let x = startX; x < endX; x++) {
      const u = (x - x0 + 0.5) / glyphW;
      const alpha = sampleGlyphAlpha(char, u, v);
      if (alpha <= 0.01) continue;
      const idx = (y * bufW + x) * 4;
      data[idx] = Math.round(data[idx] * (1 - alpha) + color[0] * alpha);
      data[idx + 1] = Math.round(data[idx + 1] * (1 - alpha) + color[1] * alpha);
      data[idx + 2] = Math.round(data[idx + 2] * (1 - alpha) + color[2] * alpha);
      data[idx + 3] = 255;
    }
  }
}
